/** Replaces each {name} in the prompt with values[name]; anything else in braces (the JSON example) is left alone. */
export function fillPrompt(values, text = ASTRA_PROMPT) {
  return text.replace(/\{([a-z_]+)\}/g, (whole, name) => (Object.hasOwn(values, name) ? String(values[name]) : whole));
}
