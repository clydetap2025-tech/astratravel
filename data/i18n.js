export const tr = (key, language) => copy[key]?.[language] ?? copy[key]?.ru ?? key;
export const countryName = (code, language) => code === "OTHER"
  ? tr("other", language)
  : new Intl.DisplayNames([locales[language]], { type: "region" }).of(code);

export function dayCount(count, language) {
  if (language === "ru") return count + (count === 1 ? " день" : " дня");
  if (language === "kk") return count + " күн";
  if (language === "ja") return count + "日";
  return count + (count === 1 ? " day" : " days");
}

/** Count noun for a number; Russian labels hold "one|few|many" forms. */
export function countLabel(count, key, language) {
  const forms = tr(key, language).split("|");
  if (forms.length < 3) return forms[0];
  const tens = count % 100;
  const ones = count % 10;
  if (tens > 10 && tens < 20) return forms[2];
  return ones === 1 ? forms[0] : ones > 1 && ones < 5 ? forms[1] : forms[2];
}

/** Fills the "{n}" slot of a message. */
export const fill = (key, language, value, more) => tr(key, language).replace("{n}", String(value)).replace("{m}", String(more ?? ""));

export function personCount(count, language) {
  if (language === "ru") return count + (count === 1 ? " пассажир" : count < 5 ? " пассажира" : " пассажиров");
  if (language === "kk") return count + " жолаушы";
  if (language === "ja") return count + "人";
  return count + (count === 1 ? " traveller" : " travellers");
}

export function timeSpan(minutes, language) {
  const hours = Math.floor(minutes / 60);
  const rest = minutes % 60;
  const [h, m] = ({ ru: [" ч", " мин"], kk: [" сағ", " мин"], en: ["h", "m"], ja: ["時間", "分"] })[language];
  return [hours ? hours + h : "", rest ? rest + m : ""].filter(Boolean).join(" ");
}
