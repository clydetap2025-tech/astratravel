// Writes supabase/seed.sql from the JavaScript catalog, so data/ stays the single source of truth.
// Run: node scripts/supabase-seed.mjs
import { writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { photoCredits } from "../data/photos.js";
import { budgets, cities, origins, places } from "../data/catalog.js";
import { travellers } from "../data/travellers.js";
import { MAP_POINTS } from "../data/map-points.js";

const text = (value) => value == null ? "null" : "'" + String(value).replaceAll("'", "''") + "'";
const json = (value) => text(JSON.stringify(value)) + "::jsonb";
const rows = (list) => list.map((row) => "  (" + row.join(", ") + ")").join(",\n");

const sql = [
  "-- Generated by scripts/supabase-seed.mjs from data/*.js. Edit the data files, then run the script again.",
  "",
  "insert into public.countries (code, sort_order) values",
  rows(origins.map((code, index) => [text(code), index])),
  "on conflict (code) do update set sort_order = excluded.sort_order;",
  "",
  "insert into public.budgets (level, daily_kzt) values",
  rows(Object.entries(budgets).map(([level, kzt]) => [text(level), kzt])),
  "on conflict (level) do update set daily_kzt = excluded.daily_kzt;",
  "",
  "insert into public.cities (id, name, region, airport, lat, lng, sort_order) values",
  rows(cities.map((city, index) => [text(city.id), json(city.name), json(city.region), text(city.airport), city.lat, city.lng, index])),
  "on conflict (id) do update set name = excluded.name, region = excluded.region, airport = excluded.airport, lat = excluded.lat, lng = excluded.lng, sort_order = excluded.sort_order;",
  "",
  "insert into public.places (id, city_id, category, zone, minutes, cost_kzt, title, location, address, summary, tip, map_query, source_url, has_photo, map_x, map_y, sort_order) values",
  rows(places.map((place, index) => {
    const point = MAP_POINTS[place.id];
    return [text(place.id), text(place.city), text(place.category), text(place.zone), place.minutes, place.cost === null ? "null" : place.cost, json(place.title), json(place.location),
      json(place.address), json(place.summary), json(place.tip), text(place.map), text(place.source),
      "photo" in place && place.photo === false ? "false" : "true", point ? Math.round(point.x) : "null", point ? Math.round(point.y) : "null", index];
  })),
  "on conflict (id) do update set city_id = excluded.city_id, category = excluded.category, zone = excluded.zone, minutes = excluded.minutes, cost_kzt = excluded.cost_kzt,",
  "  title = excluded.title, location = excluded.location, address = excluded.address, summary = excluded.summary, tip = excluded.tip,",
  "  map_query = excluded.map_query, source_url = excluded.source_url, has_photo = excluded.has_photo, map_x = excluded.map_x, map_y = excluded.map_y,",
  "  sort_order = excluded.sort_order;",
  "",
  "delete from public.place_matches;",
  "insert into public.place_matches (place_id, country_code) values",
  rows(places.flatMap((place) => ("match" in place ? place.match ?? [] : []).map((code) => [text(place.id), text(code)]))),
  "on conflict do nothing;",
  "",
  // Photo credits (data/photos.js), the 2GIS link of eateries and coordinates where the data has them.
  // Columns from 20261128000200_content_admin.sql; a photo is only linked when it has an author and a licence.
  "update public.places p set photo_url = v.photo_url, photo_author = v.photo_author, photo_license = v.photo_license,",
  "  photo_page = v.photo_page, photo_kind = v.photo_kind, twogis_url = v.twogis_url, lat = v.lat, lng = v.lng",
  "from (values",
  rows(places.map((place) => {
    const credit = photoCredits[place.id];
    const file = existsSync(new URL("../public/assets/" + place.id + ".webp", import.meta.url));
    const photo = credit && file && credit.author && credit.license;
    return [text(place.id), photo ? text("/assets/" + place.id + ".webp") : "null::text", photo ? text(credit.author.slice(0, 200)) : "null::text",
      photo ? text(credit.license.slice(0, 80)) : "null::text", photo && credit.page?.startsWith("https://") ? text(credit.page) : "null::text",
      photo && ["place", "city", "dish"].includes(credit.kind) ? text(credit.kind) : "null::text",
      typeof place.twogis === "string" && place.twogis.startsWith("https://") ? text(place.twogis) : "null::text",
      typeof place.lat === "number" ? place.lat.toFixed(6) + "::numeric" : "null::numeric", typeof place.lng === "number" ? place.lng.toFixed(6) + "::numeric" : "null::numeric"];
  })),
  ") as v (id, photo_url, photo_author, photo_license, photo_page, photo_kind, twogis_url, lat, lng)",
  "where p.id = v.id;",
  "",
  "insert into public.country_points (country_code, lat, lng, sort_order) values",
  rows(travellers.map((item, index) => [text(item.country), item.lat, item.lng, index])),
  "on conflict (country_code) do update set lat = excluded.lat, lng = excluded.lng, sort_order = excluded.sort_order;",
  "",
].join("\n");

await writeFile(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("Wrote supabase/seed.sql: " + cities.length + " cities, " + places.length + " places, " + travellers.length + " country points.");
