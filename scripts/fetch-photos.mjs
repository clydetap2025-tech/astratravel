/**
 * Downloads one freely licensed photo per place from Wikimedia Commons and writes the credits.
 *
 *   node scripts/fetch-photos.mjs            # every place that has no photo yet
 *   node scripts/fetch-photos.mjs medeu sauran   # only these ids (re-fetch)
 *
 * For each place it tries the Wikipedia articles listed in PHOTO_SOURCES below, in order, and takes
 * the article's lead image if that image lives on Commons under a free licence (CC or public domain)
 * and is a photo (JPEG). The image is resized to 960 px wide WebP in public/assets/<id>.webp and
 * its author, licence and file page go to data/photos.js, which the app shows under every photo.
 * Requests are spaced out to stay well inside Wikimedia's rate limits.
 */
import { execFile } from "node:child_process";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";
import { places } from "../data/catalog.js";
import { PHOTO_SOURCES } from "../data/photo-sources.js";

const run = promisify(execFile);
const root = new URL("../", import.meta.url);
const assets = new URL("public/assets/", root);
const creditsFile = new URL("data/photos.js", root);
const tmp = new URL(".data/photos-tmp/", root);
const UA = "AstraTravel-demo/1.0 (travel guide demo; photo credits kept)";
const pause = (ms) => new Promise((done) => setTimeout(done, ms));

async function api(host, params) {
  const url = "https://" + host + "/w/api.php?" + new URLSearchParams({ format: "json", formatversion: "2", origin: "*", ...params });
  for (let attempt = 0; attempt < 6; attempt += 1) {
    const response = await fetch(url, { headers: { "user-agent": UA } });
    if (response.status === 429) { await pause(12000 * (attempt + 1)); continue; }
    if (!response.ok) throw new Error(host + " " + response.status);
    return response.json();
  }
  throw new Error(host + " keeps rate limiting");
}

const strip = (html = "") => html.replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();

/** The lead image of an article, if it is a free photo on Commons. */
async function leadImage(source) {
  const [lang, title] = source.split(":", 2);
  const page = await api(lang + ".wikipedia.org", { action: "query", prop: "pageimages", piprop: "name", titles: title, redirects: "1" });
  const name = page.query?.pages?.[0]?.pageimage;
  if (!name || !/\.jpe?g$/i.test(name)) return null;
  await pause(2000);
  const info = await api("commons.wikimedia.org", {
    action: "query", prop: "imageinfo", titles: "File:" + name, iiprop: "url|extmetadata|mime", iiurlwidth: "960",
  });
  const file = info.query?.pages?.[0];
  const image = file?.imageinfo?.[0];
  if (!image || file.missing) return null;
  const meta = image.extmetadata ?? {};
  const license = meta.LicenseShortName?.value ?? "";
  if (meta.NonFree?.value === "true" || !/^(CC|Public domain|PD)/i.test(license)) return null;
  return {
    url: image.thumburl ?? image.url, file: "File:" + name, page: image.descriptionurl,
    author: strip(meta.Artist?.value).slice(0, 80) || "Wikimedia Commons", license, licenseUrl: meta.LicenseUrl?.value ?? "",
    article: source,
  };
}

async function readCredits() {
  if (!existsSync(creditsFile)) return {};
  const text = await readFile(creditsFile, "utf8");
  return JSON.parse(text.slice(text.indexOf("{"), text.lastIndexOf("}") + 1));
}

const only = new Set(process.argv.slice(2));
const credits = await readCredits();
await mkdir(tmp, { recursive: true });
const missing = [];
for (const place of places) {
  if (only.size ? !only.has(place.id) : (place.photo !== false || credits[place.id])) continue;
  const sources = PHOTO_SOURCES[place.id];
  if (!sources) { missing.push(place.id + " (no sources listed)"); continue; }
  let found = null;
  for (const [kind, source] of sources) {
    try { found = await leadImage(source); } catch (error) { console.warn(place.id, source, error.message); }
    await pause(2500);
    if (found) { found.kind = kind; break; }
  }
  if (!found) { missing.push(place.id); continue; }
  const raw = new URL(place.id + ".jpg", tmp);
  const response = await fetch(found.url, { headers: { "user-agent": UA } });
  if (!response.ok) { missing.push(place.id + " (download " + response.status + ")"); continue; }
  await writeFile(raw, Buffer.from(await response.arrayBuffer()));
  await run("magick", [fileURLToPath(raw), "-auto-orient", "-resize", "960x720^", "-gravity", "center", "-extent", "960x720", "-strip", "-quality", "66", fileURLToPath(new URL(place.id + ".webp", assets))]);
  delete found.url;
  credits[place.id] = found;
  console.log("✓", place.id, "←", found.article, "·", found.license);
  await writeFile(creditsFile, "// Generated by scripts/fetch-photos.mjs: where each place photo comes from and under which licence.\n" +
    "export const photoCredits = " + JSON.stringify(credits, null, 2) + ";\n");
  await pause(2500);
}
await rm(tmp, { recursive: true, force: true });
console.log(missing.length ? "Without a photo: " + missing.join(", ") : "Every place has a photo.");
